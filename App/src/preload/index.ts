import { contextBridge, ipcRenderer } from 'electron'

const suscribir = <T>(canal: string, cb: (v: T) => void) => {
  const f = (_e: unknown, v: T) => cb(v)
  ipcRenderer.on(canal, f)
  return () => { ipcRenderer.removeListener(canal, f) }
}

